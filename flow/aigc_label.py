"""Implicit AI-generation label inside audio files (隐式标识; 2026-11-25, 《人工智能生成合成内容标识办法》第五条, the
format of GB 45438-2025 附录 E as the open-source implementation github.com/gtkit/aigc writes it — the national
standards system does not show the standard's full text yet, so check it against the text when it can be read).

An MP3 gets one ID3v2 TXXX frame with the description "AIGC" whose value is compact JSON:
    {"Label":"1","ContentProducer":"<provider code>","ProduceID":"<id unique to the provider>"}
Label "1" = generated by AI. Values are visible ASCII only (0x20-0x7E). The audio itself is not touched: a file that
already has an ID3 tag (CosyVoice's come with LAME's) gets the frame added to that tag; one without gets a new v2.4
tag. A tag this module cannot safely extend (unsynchronised, extended header, footer) is left as it is."""
import json
import re

PROVIDER = 'FlowLang'  # 生成合成服务提供者的编码（ASCII）。公司成立后换成公司名称或编码（语流 23，2026-11-25）
DESC = b'AIGC'
ASCII = re.compile(r'^[\x20-\x7e]+$')


def value(produce_id, provider=PROVIDER):
    v = {'Label': '1', 'ContentProducer': provider, 'ProduceID': produce_id}
    for k, x in v.items():
        if not isinstance(x, str) or not ASCII.match(x):
            raise ValueError('AIGC field %s must be visible ASCII' % k)
    return json.dumps(v, separators=(',', ':')).encode('ascii')


def _syncsafe(n):
    return bytes([(n >> 21) & 0x7f, (n >> 14) & 0x7f, (n >> 7) & 0x7f, n & 0x7f])


def _unsync(b):
    return (b[0] << 21) | (b[1] << 14) | (b[2] << 7) | b[3]


def has_label(data):
    """Does this MP3 already carry an AIGC frame?"""
    try:
        return read(data) is not None
    except (ValueError, UnicodeDecodeError):
        return False


def mp3(data, produce_id, provider=PROVIDER):
    """data with the AIGC frame in its ID3 tag (unchanged when it already has one or the tag cannot be extended)."""
    if has_label(data):
        return data
    body = value(produce_id, provider)
    if data[:3] == b'ID3' and len(data) >= 10:
        major, flags = data[3], data[5]
        if major not in (3, 4) or flags & 0xd0 or flags & 0x40:  # unsynchronisation / extended header / footer: leave it
            return data
        size = _unsync(data[6:10])
        enc = b'\x00' if major == 3 else b'\x03'  # ISO-8859-1 in v2.3, UTF-8 in v2.4 (ASCII is both)
        content = enc + DESC + b'\x00' + body
        head = b'TXXX' + (len(content).to_bytes(4, 'big') if major == 3 else _syncsafe(len(content))) + b'\x00\x00'
        frame = head + content
        return data[:6] + _syncsafe(size + len(frame)) + frame + data[10:]
    content = b'\x03' + DESC + b'\x00' + body
    frame = b'TXXX' + _syncsafe(len(content)) + b'\x00\x00' + content
    return b'ID3\x04\x00\x00' + _syncsafe(len(frame)) + frame + data


def read(data):
    """The AIGC value of an MP3 (dict) or None: for checks and tests."""
    if data[:3] != b'ID3':
        return None
    major, size = data[3], _unsync(data[6:10])
    tag, i = data[10:10 + size], 0
    while i + 10 <= len(tag) and tag[i:i + 4] != b'\0\0\0\0':
        n = int.from_bytes(tag[i + 4:i + 8], 'big') if major == 3 else _unsync(tag[i + 4:i + 8])
        fid, content = tag[i:i + 4], tag[i + 10:i + 10 + n]
        if fid == b'TXXX' and content[1:1 + len(DESC) + 1] == DESC + b'\x00':
            return json.loads(content[2 + len(DESC):].decode('utf-8'))
        i += 10 + n
    return None
